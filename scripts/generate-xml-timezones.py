"""Generate immutable UTC transition tables and an independent TZif oracle from pinned tzdata.

Runtime uses only the generated table. Regeneration needs CPython's zoneinfo parser,
but requires no installed timezone package and never consults host TZPATH.
"""
import argparse
from datetime import datetime, timezone
import hashlib
import io
import json
from pathlib import Path
import tarfile
import zipfile
from zoneinfo import ZoneInfo, _common
from zoneinfo._zoneinfo import _parse_tz_str

parser = argparse.ArgumentParser()
parser.add_argument('--wheel', type=Path, default=Path('.deps/timezone-data/tzdata-2026.6-py2.py3-none-any.whl'))
parser.add_argument('--source', type=Path, default=Path('.deps/timezone-data/tzdata2026f.tar.gz'))
parser.add_argument('--output', type=Path, default=Path('resources/timezones'))
args = parser.parse_args()
wheel_hash = '0a10eec6e13ef16b627fabed9a5f2ba61a62b1c67f327305f4e7e412a70b4aec'
source_hash = '01b4a91cec5167ed48c11e8ab78f2048cead78ce94b0cafcad0ae8c5a3044d3d'
sha = lambda b: hashlib.sha256(b).hexdigest()
assert sha(args.wheel.read_bytes()) == wheel_hash
assert sha(args.source.read_bytes()) == source_hash
wheel = zipfile.ZipFile(args.wheel)
assert 'IANA_VERSION = "2026f"' in wheel.read('tzdata/__init__.py').decode()
names = sorted(set(wheel.read('tzdata/zones').decode().splitlines()) - {'Factory'})
epoch_end = 4133980800  # 2101-01-01T00:00:00Z, exclusive.
patterns, ids, zone_rows, binary = [], {}, [], {}
for name in names:
    raw = wheel.read('tzdata/zoneinfo/' + name)
    z = ZoneInfo.from_file(io.BytesIO(raw), key=name)
    indices, times, offsets, dst, abbrev, tail = _common.load_data(io.BytesIO(raw))
    points = {0, *(t for t in times if 0 < t < epoch_end)}
    if tail:
        rule = _parse_tz_str(tail.decode())
        if hasattr(rule, 'transitions'):
            for year in range(1969, 2102):
                start, end = rule.transitions(year)
                for instant in (int(start - rule.std.utcoff.total_seconds()), int(end - rule.dst.utcoff.total_seconds())):
                    if (not times or instant > times[-1]) and 0 < instant < epoch_end:
                        points.add(instant)
    entries = []
    for instant in sorted(points):
        offset = int(datetime.fromtimestamp(instant, timezone.utc).astimezone(z).utcoffset().total_seconds())
        if not entries or entries[-1][1] != offset:
            entries.append((instant, offset))
    key = tuple(entries)
    if key not in ids:
        ids[key] = len(patterns)
        patterns.append(entries)
    zone_rows.append((name, ids[key]))
    binary[name] = raw
output = args.output
output.mkdir(parents=True, exist_ok=True)
lines = [f'P\t{i}\t' + ','.join(f'{t}:{o}' for t, o in rows) for i, rows in enumerate(patterns)]
lines += [f'Z\t{name}\t{i}' for name, i in zone_rows]
table = '// Generated by scripts/generate-xml-timezones.py; IANA2026f, UTC [1970,2101).\n' + '\n'.join('R"PPMTZ(' + line + ')PPMTZ",' for line in lines) + '\n'
(output / 'tzdb-2026f.inc').write_text(table, encoding='ascii', newline='\n')
with zipfile.ZipFile(output / 'tzif-2026f.zip', 'w', compression=zipfile.ZIP_DEFLATED, compresslevel=9) as archive:
    for name, raw in binary.items():
        info = zipfile.ZipInfo(name, (1980, 1, 1, 0, 0, 0))
        info.create_system = 0
        info.compress_type = zipfile.ZIP_DEFLATED
        info.external_attr = 0o644 << 16
        archive.writestr(info, raw, compresslevel=9)
source = tarfile.open(args.source)
(output / 'LICENSE-IANA.txt').write_bytes(source.extractfile('LICENSE').read())
(output / 'LICENSE-python-tzdata.txt').write_bytes(wheel.read('tzdata-2026.6.dist-info/licenses/LICENSE'))
(output / 'LICENSE-APACHE-2.0.txt').write_bytes(wheel.read('tzdata-2026.6.dist-info/licenses/licenses/LICENSE_APACHE'))
manifest = dict(version='2026f', wheel_version='2026.6', utc_start='1970-01-01T00:00:00Z', utc_finish_exclusive='2101-01-01T00:00:00Z',
                wheel_url='https://files.pythonhosted.org/packages/0a/66/9a06c2227fedfd4919f0eaaa8b94377d9730882a7e4f95823c9a331ab5e1/tzdata-2026.6-py2.py3-none-any.whl',
                wheel_sha256=wheel_hash, source_url='https://data.iana.org/time-zones/releases/tzdata2026f.tar.gz', source_sha256=source_hash,
                zones=len(names), patterns=len(patterns), transitions=sum(len(p) for p in patterns),
                excluded_placeholder='Factory', files={name: sha((output / name).read_bytes()) for name in ('tzdb-2026f.inc', 'tzif-2026f.zip', 'LICENSE-IANA.txt', 'LICENSE-python-tzdata.txt', 'LICENSE-APACHE-2.0.txt')})
(output / 'manifest.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=2), encoding='utf-8', newline='\n')
print(json.dumps({k: manifest[k] for k in ('version', 'zones', 'patterns', 'transitions', 'files')}, indent=2))
