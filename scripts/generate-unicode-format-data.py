"""Generate pinned, locale-independent XML StrConv tables from Unicode 16 UCD.

Usage: python scripts/generate-unicode-format-data.py path/to/UCD.zip
No host case mapping or host Unicode version is used.
"""
import hashlib
import json
from pathlib import Path
import sys
import zipfile

source = Path(sys.argv[1])
out = Path(__file__).resolve().parents[1] / 'resources/text'
out.mkdir(parents=True, exist_ok=True)
z = zipfile.ZipFile(source)
assert '16.0.0' in z.read('ReadMe.txt').decode('utf-8')
case = {}
wide = {}
compose = {}
for line in z.read('UnicodeData.txt').decode('utf-8').splitlines():
    p = line.split(';')
    cp = int(p[0], 16)
    case[cp] = [p[12] or p[0], p[13] or p[0], p[14] or p[12] or p[0]]
    d = p[5].split()
    if d and d[0] == '<wide>':
        wide[int(d[1], 16)] = cp
    if d and d[0] == '<narrow>':
        wide[cp] = int(d[1], 16)
    if len(d) == 2 and not d[0].startswith('<') and d[1] in ('3099', '309A'):
        compose[(int(d[0], 16), int(d[1], 16))] = cp
for line in z.read('SpecialCasing.txt').decode('utf-8').splitlines():
    p = line.split('#')[0].strip().split(';')
    if len(p) >= 5 and not p[4].strip():
        case[int(p[0], 16)] = [p[3].strip(), p[1].strip(), p[2].strip()]
rows = []
for cp, mappings in sorted(case.items()):
    for mode, mapping in enumerate(mappings):
        targets = [int(c, 16) for c in mapping.split()]
        if targets != [cp]:
            rows.append('C %X %d %s' % (cp, mode, ' '.join('%X' % n for n in targets)))
for a, b in sorted(wide.items()):
    rows.append('W %X %X' % (a, b))
for (a, b), c in sorted(compose.items()):
    rows.append('P %X %X %X' % (a, b, c))
for line in z.read('DerivedCoreProperties.txt').decode('utf-8').splitlines():
    p = line.split('#')[0].strip().split(';')
    if len(p) == 2 and p[1].strip() in ('Cased', 'Case_Ignorable'):
        r = p[0].strip().split('..')
        rows.append('%s %s %s' % ('A' if p[1].strip() == 'Cased' else 'I', r[0], r[-1]))
data = '// Generated by scripts/generate-unicode-format-data.py. Unicode License V3.\n'
data += 'R"PPMUCD(\n' + '\n'.join(rows) + '\n)PPMUCD"\n'
(out / 'unicode-16.0.0.inc').write_text(data, encoding='utf-8', newline='\n')
manifest = dict(version='16.0.0', source='https://www.unicode.org/Public/16.0.0/ucd/UCD.zip',
                source_sha256=hashlib.sha256(source.read_bytes()).hexdigest(),
                table_sha256=hashlib.sha256(data.encode()).hexdigest(), records=len(rows),
                files={n: hashlib.sha256(z.read(n)).hexdigest() for n in
                       ['UnicodeData.txt', 'SpecialCasing.txt', 'DerivedCoreProperties.txt']})
(out / 'manifest.json').write_text(json.dumps(manifest, indent=2) + '\n', encoding='utf-8')
print(json.dumps(manifest))
